def build_log() -> str:
    out = ["# GuideRail: Evaluation Log (dev split)", "",
           "_Generated by `evaluation/build_summary.py` from the tagged dev reports. Do not edit by hand._", "",
           "How changes were chosen: each candidate change was measured on the **dev** split only. A change was kept if it improved the target "
           "metric on both corpora without hurting validated precision or out-of-corpus false accepts; otherwise it was reverted. Acceptance rules were "
           "fixed before looking at each run's results. All rows below are re-scored with the *current* answer-matching rules so they are comparable. "
           "**Real-corpus rows up to the tightened LLM prompt describe the 3-document corpus; the last two steps use the 5-document corpus "
           "and a larger dev set, so they are not directly comparable with the earlier real rows.**", "",
           "| Step | Corpus | Hit@5 | MRR | Answer correct | Validated precision | OOC false accept | Decision accuracy |", "|---|---|---|---|---|---|---|---|"]
    notes = []
    for tag, gen, name, what, verdict in STEPS:
        for c in ("synthetic", "real"):
            rep = load(c, "dev", gen, tag)
            if rep is None:
                continue
            rep = rescored(rep)
            s = summarize(rep["records"], 0.6)
            r = rep["retrieval"]
            out.append(f"| {name} | {c} | {pct(r['hit@5'])} | {r['mrr']:.3f} | {pct(s['in_corpus']['answer_correct_rate'])} | "
                       f"{pct(s['in_corpus']['validated_precision'])} | {pct(s['out_of_corpus']['false_accept_rate'])} | {pct(s['decision_accuracy'])} |")
        notes.append(f"- **{name.strip()}**: {what} {verdict}")
    out += ["", "## What each step was and what was decided", "", *notes, "",
            "## Experiments not reproducible from the repository", "",
            "- **IDF-weighted embeddings** (two variants) were tried on retrieval only and **rejected**: they raised Hit@5 on some corpora but lowered "
            "MRR on both, failing the rule. The code was reverted. Console figures at the time: synthetic dev MRR 0.690 → 0.647 and 0.655, real dev "
            "MRR 0.483 → 0.471 for both variants.",
            "",
            "## Label edits made after seeing dev outputs",
            "",
            "- **S09**: added the alternative \"should not be worn between patients\" to the expected fact, after an LLM answer used that correct "
            "paraphrase and was scored wrong. Answer matching was also made stem-aware (\"acts\" matches \"act\"), which applies to every system equally.",
            "- **Stress set**: cases touching a test-split topic were re-worded so no test-split question text is used in development.",
            ""]
    return "\n".join(out)


