"""Generate docs/EVALUATION_REPORT.md and docs/EVALUATION_LOG.md from the saved report files.

    python evaluation/build_summary.py

Every number in the output is read from evaluation/reports/*.json; none is typed by hand. The
narrative around the tables is deliberately qualitative. Re-run this after any evaluation run.
"""

from __future__ import annotations

import json

from common import CORPORA, REPORTS, ROOT

from guiderail import config
from guiderail.evalkit import answer_correct, load_queries, summarize, sweep, wilson
from guiderail.retriever import RERANK_POOL

DOCS = ROOT / "docs"


def load(c: str, split: str, gen: str, tag: str) -> dict | None:
    path = REPORTS / f"{c}_{split}_{gen}_{tag}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def ci(k: int, n: int) -> str:
    w = wilson(k, n)
    return "n/a" if w is None else f"{100 * k / n:.0f}% ({100 * w[0]:.0f}–{100 * w[1]:.0f})"


def real_agencies() -> str:
    sources = json.loads((CORPORA["real"]["dir"] / "sources.json").read_text(encoding="utf-8"))
    return " and ".join(sorted({d["agency"] for d in sources["documents"]}))


def counts(report: dict, threshold: float = 0.6) -> dict:
    recs = report["records"]
    inc = [r for r in recs if r["kind"] == "in_corpus"]
    ooc = [r for r in recs if r["kind"] != "in_corpus"]
    ok = lambda r: r["confidence"] >= threshold and r["cited"]
    val = [r for r in inc if ok(r)]
    return {"n_in": len(inc), "n_ooc": len(ooc), "validated": len(val),
            "correct": sum(1 for r in inc if r["correct"]),
            "val_correct": sum(1 for r in val if r["correct"]),
            "ooc_accepted": sum(1 for r in ooc if ok(r)),
            "correct_flagged": sum(1 for r in inc if r["correct"] and not ok(r))}


def rescored(report: dict) -> dict:
    """Recompute `correct` with the current labels/matching so old and new runs compare fairly."""
    queries = {q.id: q for q in load_queries(CORPORA[report["corpus"]]["queries"])}
    for r in report["records"]:
        q = queries[r["id"]]
        r["correct"] = answer_correct(r["answer"], q) if q.kind == "in_corpus" else None
    return report


