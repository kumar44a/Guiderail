"""Keep the documents' numbers tied to the artifacts they come from.

    python scripts/check_docs_sync.py            # check only; exit 1 if anything is out of date
    python scripts/check_docs_sync.py --write    # regenerate the README stats block and docs/EVALUATION_*.md

What it checks:
  1. The block between <!-- stats:start --> and <!-- stats:end --> in README.md equals what
     the saved evaluation reports (evaluation/reports/*_final.json) say.
  2. docs/EVALUATION_REPORT.md and docs/EVALUATION_LOG.md equal what evaluation/build_summary.py
     generates from those same reports.
  3. The README does not state counts that the stats block owns (a loose guard against hand-typed numbers).
Nothing here runs a model or the network.
"""

from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "evaluation")]

import build_summary as bs  # noqa: E402
from common import REPORTS  # noqa: E402

README = ROOT / "README.md"
START, END = "<!-- stats:start -->", "<!-- stats:end -->"


def collected_tests() -> int | None:
    proc = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q"], cwd=ROOT,
                          capture_output=True, text=True, encoding="utf-8")
    match = re.search(r"(\d+) tests? collected", proc.stdout) or re.search(r"(\d+) tests? collected", proc.stderr)
    return int(match.group(1)) if match else None


def stats_block() -> str:
    syn = bs.load("synthetic", "test", "extractive", "final")
    real = bs.load("real", "test", "extractive", "final")
    tests = collected_tests()
    lines = [START, "_Generated by `scripts/check_docs_sync.py --write` from `evaluation/reports/`. Do not edit by hand._", "",
             f"- Synthetic corpus: {syn['manifest_counts']['documents']} documents, {syn['manifest_counts']['chunks']} chunks "
             f"({syn['manifest_counts']['superseded_documents']} superseded versions).",
             f"- Real corpus: {real['manifest_counts']['documents']} PDFs from {bs.real_agencies()}, {real['manifest_counts']['chunks']} chunks.",
             f"- Index hash of the synthetic corpus at evaluation time: `{syn['index_sha256']}`.",
             f"- Tests collected: {tests if tests is not None else 'unknown (pytest not available)'}.",
             f"- Threshold {bs.config.DEFAULT_THRESHOLD}; lexical re-ranker weight {bs.config.DEFAULT_RERANK_WEIGHT}.", "",
             "**Held-out test split, threshold 0.6** (95% Wilson interval in brackets; samples are small, so read "
             "[the full report](docs/EVALUATION_REPORT.md) before comparing rows):", "",
             "| Corpus / generator | In-corpus n | Pass | Answer correct | Validated precision | Out-of-scope wrongly validated |",
             "|---|---|---|---|---|---|"]
    for corpus in ("synthetic", "real"):
        for gen in ("extractive", "llm"):
            k = bs.counts(bs.rescored(bs.load(corpus, "test", gen, "final")))
            lines.append(f"| {corpus} / {gen} | {k['n_in']} | {bs.ci(k['validated'], k['n_in'])} | {bs.ci(k['correct'], k['n_in'])} | "
                         f"{bs.ci(k['val_correct'], k['validated']) if k['validated'] else 'n/a'} | {k['ooc_accepted']} of {k['n_ooc']} |")
    s, r = syn["retrieval"], real["retrieval"]
    lines += ["", "| Retrieval (test split) | Precision@5 | Capped Precision@5 | Hit@5 | MRR |", "|---|---|---|---|---|",
              f"| synthetic | {bs.pct(s['precision@5'])} | {bs.pct(s['capped_precision@5'])} | {bs.pct(s['hit@5'])} | {s['mrr']:.3f} |",
              f"| real | {bs.pct(r['precision@5'])} | {bs.pct(r['capped_precision@5'])} | {bs.pct(r['hit@5'])} | {r['mrr']:.3f} |",
              END]
    return "\n".join(lines)


def render_readme(current: str, block: str) -> str:
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(current):
        raise SystemExit(f"README.md has no {START} ... {END} block")
    return pattern.sub(lambda _m: block, current)


def diff(name: str, old: str, new: str) -> str:
    return "".join(difflib.unified_diff(old.splitlines(True), new.splitlines(True), f"{name} (current)", f"{name} (expected)", n=1))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--write", action="store_true", help="rewrite the generated parts instead of failing")
    args = parser.parse_args()

    expected: dict[Path, str] = {
        README: render_readme(README.read_text(encoding="utf-8"), stats_block()),
        ROOT / "docs" / "EVALUATION_REPORT.md": bs.build_report(),
        ROOT / "docs" / "EVALUATION_LOG.md": bs.build_log(),
    }
    problems = []
    for path, text in expected.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == text:
            continue
        if args.write:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"updated {path.relative_to(ROOT)}")
        else:
            problems.append(f"{path.relative_to(ROOT)} is out of date:\n{diff(path.name, current, text)}")

    readme_outside = re.sub(re.escape(START) + r".*?" + re.escape(END), "", expected[README], flags=re.DOTALL)
    for pattern, what in ((r"\b\d[\d,]*\s+(documents|chunks|tests)\b", "a document, chunk or test count"),
                          (r"\bP(recision)?@\d+\s*(=|of|:)?\s*\d", "a Precision@K figure"),
                          (r"\b\d{2,3}(\.\d)?\s?%", "a percentage")):
        for m in re.finditer(pattern, readme_outside):
            problems.append(f"README.md states {what} outside the generated block: {m.group(0)!r}")

    if problems:
        print("\n\n".join(problems), file=sys.stderr)
        return 1
    print("docs are in sync with the reports" if not args.write else "done")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
